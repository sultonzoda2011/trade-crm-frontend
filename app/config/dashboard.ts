import type { Period } from '~/config/period';

/**
 * Настройки главного экрана владельца (`/dashboard`).
 *
 * Здесь только то, что решает фронтенд. Пороги, которыми пользуется бэкенд
 * (срок «долг скоро просрочится», «запас на N дней» и т.п.), сюда не копируются:
 * они приходят в параметрах рекомендаций (`insight.params.days`).
 */

/** Период, с которым открывается «Обзор»: вечером владелец спрашивает «как прошёл день?». */
export const OVERVIEW_DEFAULT_PERIOD: Period = 'today';

/** Период остальных вкладок дашборда (склад, товары, продавцы) — как и было до редизайна обзора. */
export const DASHBOARD_DEFAULT_PERIOD: Period = 'month';

/**
 * За сколько последних дней считается «на сколько хватит запаса».
 *
 * Прогноз не может зависеть от переключателя «Сегодня / Неделя / Месяц / Год»:
 * по продажам за один день запас нельзя оценить (товар мог не продаться
 * именно сегодня), а за год продажи размазываются и срочное не видно. Четыре
 * недели — это целое число недель, поэтому будни и выходные входят поровну.
 */
export const STOCK_ANALYSIS_DAYS = 28;

/**
 * Окно короче этого числа дней нельзя честно сравнивать с прошлым периодом:
 * бэкенд сравнивает «сегодня до сих пор» с целым «вчера», и с утра любой день
 * выглядит провалом. Для таких окон вместо «−60%» показываем прошлую сумму.
 */
export const MIN_DAYS_FOR_TREND = 3;

/**
 * С какого изменения продажи категории считаются «заметно упали / выросли».
 * Совпадает с порогом бэкенда `SIGNIFICANT_CHANGE_PERCENT`, на котором строятся
 * рекомендации по общей выручке, — чтобы категории и общий итог оценивались
 * одной меркой. Бэкенд этот порог в ответе не отдаёт.
 */
export const SIGNIFICANT_CHANGE_PERCENT = 15;

/** Сколько строк показывать до «Показать все» — экран должен читаться за один взгляд. */
export const ATTENTION_VISIBLE = 4;
export const STOCK_ROWS_VISIBLE = 4;
export const LEADERS_VISIBLE = 3;
export const CATEGORY_CHANGES_VISIBLE = 4;
export const CATEGORIES_VISIBLE = 5;
export const SELLERS_VISIBLE = 5;
export const RECENT_TRANSACTIONS_LIMIT = 5;
